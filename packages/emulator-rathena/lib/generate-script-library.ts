import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { CommandRegistry } from "@runeforge/emulator-core";
import type { CommandDefinition } from "@runeforge/emulator-core";
import { parseBuiltinTable } from "../src/builtin-table";
import { parseCommandDoc } from "../src/command-doc";

const packageDirectory = dirname(fileURLToPath(import.meta.url));
const softwareDirectory = resolve(packageDirectory, "../../..");
const repositoryDirectory = resolve(softwareDirectory, "..");
const sourcePath = resolve(repositoryDirectory, "Serveur/rathena-kov/src/map/script.cpp");
const manualPath = resolve(repositoryDirectory, "Document about NPC/script_commands.txt");
const licensePath = resolve(repositoryDirectory, "Serveur/rathena-kov/LICENSE");
const outputPath = resolve(packageDirectory, "../src/script-library.ts");
const projectLicensePath = resolve(softwareDirectory, "LICENSE");

const sourceText = readFileSync(sourcePath, "utf8");
const manualText = readFileSync(manualPath, "utf8");
const source = parseBuiltinTable(sourceText, "src/map/script.cpp");
const manual = parseCommandDoc(manualText, "doc/script_commands.txt");

if (source.definitions.length < 650 || source.unrecognized.length > 0 || source.invalid.length > 0) {
  throw new Error(
    `Unexpected rAthena command table: ${source.definitions.length} commands, ${source.unrecognized.length} unrecognized lines, ${source.invalid.length} invalid definitions`,
  );
}
if (manual.definitions.length < 600) {
  throw new Error(`Unexpected rAthena command manual: only ${manual.definitions.length} documented commands`);
}

const registry = CommandRegistry.create([...source.definitions, ...manual.definitions], "rAthena");
const definitions: CommandDefinition[] = registry.definitions().map((definition) => ({
  ...definition,
  documentation:
    definition.documentation ??
    `rAthena scripting command ${definition.name}.\n\nServer argument notation: ${definition.parameterTypes ?? "not specified"}.`,
  sources: definition.sources.map((entry) => ({
    kind: "builtin-library",
    reference: `rAthena built-in library — ${entry.reference}`,
  })),
}));
const manualUpdated = /^\/\/=\s*(\d{8})\s*$/m.exec(manualText)?.[1];
if (manualUpdated === undefined) throw new Error("Could not read the manual's last-updated date");

const output = `/*
 * Generated by \`npm run generate:rathena-library\`.
 * Sources: rAthena's \`src/map/script.cpp\` and \`doc/script_commands.txt\`.
 * The manual text and this generated library are GPL-3.0-only; see \`../../../LICENSE\`.
 */
import type { CommandDefinition } from "@runeforge/emulator-core";

export const RATHENA_SCRIPT_LIBRARY_INFO = {
  source: "rathena-kov",
  commandCount: ${definitions.length},
  manualUpdated: "${manualUpdated}",
  license: "GPL-3.0-only",
} as const;

export const RATHENA_SCRIPT_LIBRARY: readonly CommandDefinition[] = ${JSON.stringify(definitions, null, 2)};
`;

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, output, "utf8");
copyFileSync(licensePath, projectLicensePath);
console.log(
  `Generated ${definitions.length} commands (${manual.definitions.length} documented, ${source.definitions.length} from source); manual updated ${manualUpdated}.`,
);
