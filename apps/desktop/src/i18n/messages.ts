export type Messages = Record<MessageKey, string>;

export const MESSAGES: Record<"en" | "fr", Messages> = { en, fr };

/** Remplace les `{parametres}` d'un message ; un parametre absent reste visible tel quel. */
export function format(template: string, params?: Readonly<Record<string, string | number>>): string {
  if (params === undefined) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = params[name];
    return value === undefined ? match : String(value);
  });
}

export function translate(language: "en" | "fr", key: MessageKey, params?: Readonly<Record<string, string | number>>): string {
  return format(MESSAGES[language][key], params);
}
